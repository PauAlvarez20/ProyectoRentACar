    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        try {
        String cedula = txtCedula.getText().trim();
        Empleados e = lista.find(cedula);
        if (e == null) { // o captura tu NoEncontradoException
            JOptionPane.showMessageDialog(this, "No existe empleado con esa cédula");
            return;
        }
        // Pasa datos al formulario
        txtNombre.setText(e.getNombre());
        txtTelefono.setText(e.getTelefono());
        txtCorreo.setText(e.getCorreo());
        txtPuesto.setText(e.getPuesto());
        txtSalario.setValue(e.getSalario());
        java.util.Date d = java.util.Date.from(e.getFechaNacimiento().atStartOfDay(java.time.ZoneId.systemDefault()).toInstant());
        spFecha.setValue(d);
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
       try {
        String cedula = txtCedula.getText().trim();
        Empleados e = lista.find(cedula);
        if (e == null) {
            JOptionPane.showMessageDialog(this, "No existe empleado con esa cédula");
            return;
        }
        int x = JOptionPane.showConfirmDialog(this, "¿Eliminar al empleado " + e.getNombre() + "?", 
                                              "Confirmar", JOptionPane.YES_NO_OPTION);
        if (x == JOptionPane.YES_OPTION) {
            lista.remove(e);
            refrescarTabla();
            btnLimpiarActionPerformed(null);
        }
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {
        String cedula = txtCedula.getText().trim();
        String nombre = txtNombre.getText().trim();
        java.util.Date fn = (java.util.Date) spFecha.getValue();
        String telefono = txtTelefono.getText().trim();
        String correo = txtCorreo.getText().trim();
        String puesto = txtPuesto.getText().trim();
        double salario = ((Number) txtSalario.getValue()).doubleValue();

        if (cedula.isBlank() || nombre.isBlank() || puesto.isBlank())
            throw new IllegalArgumentException("Cédula, nombre y puesto son obligatorios");

        // Convertir Date -> LocalDate si tu entidad usa LocalDate
        java.time.LocalDate fechaNac = fn.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();

        // Construye tu Empleados según tu constructor
        Empleados e = new Empleados(cedula, nombre, fechaNac, telefono, correo,puesto, salario);

        // Evitar duplicados (haz la validación en addEmpleado)
        lista.add(e);

        refrescarTabla();
        JOptionPane.showMessageDialog(this, "Empleado agregado");
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
       try {
        String cedula = txtCedula.getText().trim();
        String tel = txtTelefono.getText().trim();
        String cor = txtCorreo.getText().trim();
        String puesto = txtPuesto.getText().trim();

        // reutiliza tu método de servicio/lista
        // (el que hicimos antes con validaciones)
        lista.actualizarEmpleado(cedula, tel, cor, puesto);
        

        // Si quieres actualizar salario también:
        Empleados e = lista.find(cedula);
        if (e != null) {
            double salario = ((Number) txtSalario.getValue()).doubleValue();
            if (salario < 0) throw new IllegalArgumentException("El salario no puede ser negativo");
            e.setSalario(salario);
        }

        refrescarTabla();
        JOptionPane.showMessageDialog(this, "Empleado actualizado");
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnActualizarActionPerformed

