        private void refrescarTabla() {
    javax.swing.table.DefaultTableModel m =
        (javax.swing.table.DefaultTableModel) tblEmpleados.getModel();

    // borra filas actuales
    m.setRowCount(0);

    // llena con los datos de la lista
    for (Empleados e : lista.getListEmpleado()) {
        m.addRow(new Object[]{
            e.getCedula(),
            e.getNombre(),
            formatearFecha(e.getFechaNacimiento()), 
            e.getTelefono(),
            e.getCorreo(),
            e.getPuesto(),
            e.getSalario()
        });
    }
}
        private String formatearFecha(java.time.LocalDate fecha) {
    if (fecha == null) return "";
    java.time.format.DateTimeFormatter f =
        java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy");
    return fecha.format(f);
}
