    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {
        String cedula   = txtCedula.getText().trim();
        String nombre   = txtNombre.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String correo   = txtCorreo.getText().trim();
        String licencia = txtLicencia.getText().trim();
        java.util.Date fn = (java.util.Date) spFechaNac.getValue();
        java.time.LocalDate fechaNac = fn.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();

        //  Valida el constructor de Cliente (lanza si algo está mal)
        Clientes nuevo = new Clientes(cedula, nombre, fechaNac, telefono, correo, licencia);

        // Evitar duplicados (hazlo dentro de addCliente si prefieres)
        for (Clientes c : lista.getListClientes()) {
            if (c.getCedula().equals(cedula)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ya existe un cliente con esa cédula.");
                return;
            }
        }

        lista.add(nuevo);
        refrescarTabla();
        javax.swing.JOptionPane.showMessageDialog(this, "Cliente agregado.");
        btnLimpiarActionPerformed(null);

    } catch (IllegalArgumentException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), "Datos inválidos", javax.swing.JOptionPane.ERROR_MESSAGE);
    } catch (Exception ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error inesperado: " + ex.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnAgregarActionPerformed

