    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
       try {
        String cedula = txtCedula.getText().trim();
        Clientes c = lista.find(cedula);
        if (c == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "No existe cliente con esa cédula.");
            return;
        }
        txtNombre.setText(c.getNombre());
        txtTelefono.setText(c.getTelefono());
        txtCorreo.setText(c.getCorreo());
        txtLicencia.setText(c.getLicencia());
        spFechaNac.setValue(java.util.Date.from(
            c.getFechaNacimiento().atStartOfDay(java.time.ZoneId.systemDefault()).toInstant()
        ));
        // (opcional) actualizar etiqueta de edad si la pusiste
        refrescarTabla(); // si quieres resaltar visualmente que existe
    } catch (Exception ex) {
        javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnBuscarActionPerformed

