private void refrescarTabla() {
    javax.swing.table.DefaultTableModel m =
        (javax.swing.table.DefaultTableModel) tblClientes.getModel();
    m.setRowCount(0);
    for (Clientes c : lista.getListClientes()) {
        m.addRow(new Object[]{
            c.getCedula(),
            c.getNombre(),
            formatearFecha(c.getFechaNacimiento()),
            calcularEdad(c.getFechaNacimiento()),
            c.getTelefono(),
            c.getCorreo(),
            c.getLicencia()
        });
    }
}

private String formatearFecha(java.time.LocalDate fecha) {
    if (fecha == null) return "";
    var f = java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy");
    return fecha.format(f);
}
//*****************************************************************//
private int calcularEdad(java.time.LocalDate fecha) {
    return java.time.Period.between(fecha, java.time.LocalDate.now()).getYears();
}

