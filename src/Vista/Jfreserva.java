private Clientes tomarClientePorCedula(String cedula) {
    if (cedula == null || cedula.isBlank()) throw new IllegalArgumentException("Cédula vacía");
    // Ajusta al método real de tu gestor
    Clientes c = gestorClientes.find(cedula);
    if (c == null) throw new IllegalArgumentException("Cliente no existe: " + cedula);
    return c;
}
private java.time.LocalDate parseFecha(String fechaTexto) {
    try {
        return java.time.LocalDate.parse(fechaTexto.trim());
    } catch (Exception e) {
        throw new IllegalArgumentException("Formato de fecha inválido. Use yyyy-MM-dd (ej: 2025-08-29)");
    }
}

private Vehiculos tomarVehiculoPorPlaca(String placa) {
    if (placa == null || placa.isBlank()) throw new IllegalArgumentException("Placa vacía");
    // Ajusta al método real de tu gestor
    Vehiculos v = gestorVehiculos.buscarVehiculo(placa);
    if (v == null) throw new IllegalArgumentException("Vehículo no existe: " + placa);
    return v;
}

private java.time.LocalDate toLocalDate(java.util.Date date) {
    if (date == null) throw new IllegalArgumentException("Fecha no seleccionada");
    return date.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate();
}

private void refrescarTablaReservas() {
    modeloReservas.setRowCount(0);
    for (Reserva r : gestorReservas.getReservas()) {
        modeloReservas.addRow(new Object[]{
            r.getIdReserva(),
            r.getCliente().getCedula(),
            r.getVehiculo().getPlaca(),
            r.getFechaReserva(),   // ajusta getters si se llaman distinto
            r.getFechaInicio(),
            r.getVehiculo().getEstado()
        });
    }
}
