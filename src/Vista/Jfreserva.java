    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
    String ced = txtCedula.getText().trim();
    String placa = txtPlaca.getText().trim();

    java.time.LocalDate inicio = parseFecha(txtFechaInicio.getText());
    java.time.LocalDate fin    = parseFecha(txtFechaFin.getText());

    Clientes cli = tomarClientePorCedula(ced);
    Vehiculos veh = tomarVehiculoPorPlaca(placa);

    Reserva r = gestorReservas.agregarReserva(cli, veh, inicio, fin);

    javax.swing.JOptionPane.showMessageDialog(this, "Reserva creada. ID: " + r.getIdReserva());
    refrescarTablaReservas();

} catch (Exception ex) {
    javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int fila = tblReservas.getSelectedRow();
if (fila == -1) {
    javax.swing.JOptionPane.showMessageDialog(this, "Seleccione una reserva en la tabla");
    return;
}
int id = (int) modeloReservas.getValueAt(fila, 0);
boolean ok = gestorReservas.cancelarReserva(id); // TU método, sin cambios
if (ok) {
    javax.swing.JOptionPane.showMessageDialog(this, "Reserva cancelada");
    refrescarTablaReservas();
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "No se pudo cancelar (ID no encontrado)");
}
    }//GEN-LAST:event_jButton2ActionPerformed

